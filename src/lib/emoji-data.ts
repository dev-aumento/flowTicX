export type EmojiCategory = {
  id: string;
  label: string;
  emojis: string[];
};

/** Default quick reactions shown on hover before the user has used any. */
export const DEFAULT_QUICK_REACTION_EMOJIS = ["👍", "❤️", "😂", "😮", "😢"] as const;

const RECENT_REACTION_STORAGE_KEY = "tracker.recentReactionEmojis";
const MAX_RECENT_REACTION_EMOJIS = 5;

export function getRecentReactionEmojis(): string[] {
  if (typeof window === "undefined") {
    return [...DEFAULT_QUICK_REACTION_EMOJIS];
  }
  try {
    const raw = window.localStorage.getItem(RECENT_REACTION_STORAGE_KEY);
    if (!raw) return [...DEFAULT_QUICK_REACTION_EMOJIS];
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [...DEFAULT_QUICK_REACTION_EMOJIS];
    const recent = parsed
      .filter((value): value is string => typeof value === "string" && value.trim().length > 0)
      .map((value) => value.trim());
    const merged = [...recent];
    for (const emoji of DEFAULT_QUICK_REACTION_EMOJIS) {
      if (merged.length >= MAX_RECENT_REACTION_EMOJIS) break;
      if (!merged.includes(emoji)) merged.push(emoji);
    }
    return merged.slice(0, MAX_RECENT_REACTION_EMOJIS);
  } catch {
    return [...DEFAULT_QUICK_REACTION_EMOJIS];
  }
}

export function rememberRecentReactionEmoji(emoji: string) {
  if (typeof window === "undefined") return;
  const next = emoji.trim();
  if (!next) return;
  try {
    const current = getRecentReactionEmojis().filter((item) => item !== next);
    const updated = [next, ...current].slice(0, MAX_RECENT_REACTION_EMOJIS);
    window.localStorage.setItem(RECENT_REACTION_STORAGE_KEY, JSON.stringify(updated));
  } catch {
    // Ignore storage failures (private mode, quota, etc.).
  }
}

